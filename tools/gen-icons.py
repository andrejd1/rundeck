# design sizes (480 px) the field draws icons at: next to regular labels,
# and next to labels of this size or smaller (RunDeckField.drawIconLabel)
LARGE = 26
SMALL = 20


def png(name, size):
    svg = '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 24 24">%s</svg>' % (size, size, GLYPHS[name])
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)))


def main():
    names = C.ICON_NAMES
    missing = [n for n in names if n not in GLYPHS]
    assert not missing, missing
    for w in GF.RESOLUTIONS:
        ts = GF.text_scale(w)
        res = os.path.join(ROOT, "resources-round-%dx%d" % (w, w))
        out = os.path.join(res, "icons")
        os.makedirs(out, exist_ok=True)
        for f in os.listdir(out):
            os.remove(os.path.join(out, f))
        xml = ["<!-- Generated by tools/gen-icons.py -->", "<drawables>"]
        sizes = {"l": max(8, round(LARGE * ts)), "s": max(8, round(SMALL * ts))}
        for n in names:
            for k, size in sizes.items():
                png(n, size).save(os.path.join(out, "%s_%s.png" % (n, k)))
                xml.append('    <bitmap id="i_%s_%s" filename="icons/%s_%s.png"/>' % (n, k, n, k))
        xml.append("</drawables>")
        with open(os.path.join(res, "icons.xml"), "w") as f:
            f.write("\n".join(xml) + "\n")
        print(w, sizes)
    src = ["// Generated by tools/gen-icons.py", "", "import Toybox.Lang;", "",
           "// field icons by icon index (tools/catalog.py ICON_NAMES), large and small",
           "const ICONS_L as Array<ResourceId> = ["]
    src += ["    Rez.Drawables.i_%s_l," % n for n in names]
    src += ["] as Array<ResourceId>;", "", "const ICONS_S as Array<ResourceId> = ["]
    src += ["    Rez.Drawables.i_%s_s," % n for n in names]
    src += ["] as Array<ResourceId>;", ""]
    with open(os.path.join(ROOT, "source", "Icons.mc"), "w") as f:
        f.write("\n".join(src))


if __name__ == "__main__":
    main()
